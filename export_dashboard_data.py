"""
Regenerates dashboard/src/data.js from the corrected master table (+ FIRMS detection grid).

Run from repo root, after merge_weather.py:
    python export_dashboard_data.py

Needs: master_with_weather.csv  and  the FIRMS J1V CSVs (for the density map).
"""
import glob
import json
import os
import sys

import numpy as np
import pandas as pd

# ---------------- CONFIG ----------------
MASTER = "master_with_weather.csv"
FIRMS_FOLDER = r"F:\Stubble Burning\AQI Datasets"
OUT = os.path.join("dashboard", "src", "data.js")
# ----------------------------------------

WEATHER_RENAME = {
    "delhi_wind_speed_mean": "wind",
    "delhi_align_mean": "align",
    "delhi_temp_mean": "temp",
    "delhi_rh_mean": "rh",
    "delhi_blh_mean": "blh",
}


def build_daily():
    df = pd.read_csv(MASTER, parse_dates=["date"]).sort_values("date").reset_index(drop=True)
    for c in ("date", "fire_count", "avg_pm25"):
        if c not in df.columns:
            sys.exit(f"Missing column '{c}' in {MASTER}. Columns: {list(df.columns)}")

    yr = df["date"].dt.year
    totals = df.groupby(yr)["fire_count"].sum(min_count=1)
    if totals.isna().any() or (totals == 0).any():
        raise ValueError(f"A season has no fire data; fix the FIRMS merge first:\n{totals}")
    df["fire_count"] = df["fire_count"].fillna(0)

    out = pd.DataFrame({
        "date": df["date"].dt.strftime("%Y-%m-%d"),
        "season": yr,
        "day_of_season": (df["date"] - pd.to_datetime(yr.astype(str) + "-10-01")).dt.days,
        "fire_count": df["fire_count"],
        "avg_pm25": df["avg_pm25"].round(2),
    })
    if "avg_frp" in df.columns:
        out["avg_frp"] = df["avg_frp"].round(2)
    for src, dst in WEATHER_RENAME.items():
        if src in df.columns:
            out[dst] = df[src].round(2)
    print("Fires per season in dashboard data:")
    print(out.groupby("season")["fire_count"].sum().astype(int).to_string(), "\n")
    return json.loads(out.to_json(orient="records"))   # NaN -> null


def build_grid():
    """Count of all (de-duplicated) detections per 0.1-degree cell per year: [year, lon, lat, n]."""
    files = sorted(glob.glob(os.path.join(FIRMS_FOLDER, "fire_archive_J1V*.csv"))
                   + glob.glob(os.path.join(FIRMS_FOLDER, "fire_nrt_J1V*.csv")))
    if not files:
        print(f"WARNING: no FIRMS files in {FIRMS_FOLDER}; the map will be empty.")
        return []
    fire = pd.concat([pd.read_csv(f) for f in files], ignore_index=True)
    fire["acq_date"] = pd.to_datetime(fire["acq_date"])
    fire = fire.drop_duplicates(subset=["latitude", "longitude", "acq_date", "acq_time"])
    fire["year"] = fire["acq_date"].dt.year
    fire["lon_bin"] = (np.floor(fire["longitude"] * 10) / 10).round(1)
    fire["lat_bin"] = (np.floor(fire["latitude"] * 10) / 10).round(1)
    g = fire.groupby(["year", "lon_bin", "lat_bin"]).size().reset_index(name="n")
    print("Detections per year in map grid (should match the fire totals above):")
    print(g.groupby("year")["n"].sum().to_string(), "\n")
    return [[int(y), float(lo), float(la), int(n)] for y, lo, la, n in g.itertuples(index=False)]


def main():
    daily = build_daily()
    grid = build_grid()
    js = ("// AUTO-GENERATED by export_dashboard_data.py. Do not edit by hand.\n"
          f"export const DAILY = {json.dumps(daily, separators=(',', ':'))};\n"
          f"export const GRID = {json.dumps(grid, separators=(',', ':'))};\n")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(js)
    print(f"Wrote {OUT}: {len(daily)} daily rows, {len(grid)} map cells")


if __name__ == "__main__":
    main()
